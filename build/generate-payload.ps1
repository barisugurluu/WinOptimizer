#requires -Version 5.1
<#
.SYNOPSIS
    Publish klasorunden Payload.wxs uretir (WiX heat alternatifi - master plan Bolum 20.3).

.DESCRIPTION
    wix CLI heat araci WiX v4.0.5 SDK'da sikintili oldugundan, bu script publish
    ciktimizdaki her dosyayi bir WiX Component olarak PayloadFiles ComponentGroup'a ekler.
    build-installer.ps1 ve CI tarafindan WiX derlemesinden once cagrilir.

.PARAMETER PublishDir
    dotnet publish cikti klasoru.

.PARAMETER OutputFile
    Uretilecek Payload.wxs yolu (varsayilan: installer\wix\Payload.wxs).

.PARAMETER ComponentGroup
    ComponentGroup Id (Product.wxs ComponentGroupRef ile eslesmeli).

.PARAMETER DirectoryRef
    Hedef directory Id (varsayilan: INSTALLFOLDER).

.EXAMPLE
    .\generate-payload.ps1 -PublishDir ..\..\publish
#>
[CmdletBinding()]
param(
    [Parameter(Mandatory)][string]$PublishDir,
    [string]$OutputFile = (Join-Path $PSScriptRoot '..\installer\wix\Payload.wxs'),
    [string]$ComponentGroup = 'PayloadFiles',
    [string]$DirectoryRef = 'INSTALLFOLDER'
)

$ErrorActionPreference = 'Stop'

if (-not (Test-Path $PublishDir)) {
    throw "PublishDir bulunamadi: $PublishDir. Once 'dotnet publish' calistirin."
}
$PublishDir = (Resolve-Path $PublishDir).Path.TrimEnd('\') + '\'
$files = Get-ChildItem -Path $PublishDir -File

if ($files.Count -eq 0) {
    throw "PublishDir bos: $PublishDir"
}

$sb = [System.Text.StringBuilder]::new()
[void]$sb.AppendLine('<?xml version="1.0" encoding="utf-8"?>')
[void]$sb.AppendLine('<!-- AUTO-GENERATED by generate-payload.ps1. Duzenleme yapma. -->')
[void]$sb.AppendLine('<Wix xmlns="http://wixtoolset.org/schemas/v4/wxs">')
[void]$sb.AppendLine('  <Fragment>')
[void]$sb.AppendLine("    <ComponentGroup Id=`"$ComponentGroup`">")

$i = 0
foreach ($f in $files) {
    $id = 'comp_{0:X4}' -f $i
    [void]$sb.AppendLine("      <Component Id=`"$id`" Directory=`"$DirectoryRef`" Bitness=`"always64`">")
    [void]$sb.AppendLine("        <File Source=`"$($f.FullName)`" KeyPath=`"yes`" />")
    [void]$sb.AppendLine('      </Component>')
    $i++
}

[void]$sb.AppendLine('    </ComponentGroup>')
[void]$sb.AppendLine('  </Fragment>')
[void]$sb.AppendLine('</Wix>')

$outDir = Split-Path $OutputFile -Parent
if (-not (Test-Path $outDir)) { New-Item -ItemType Directory -Path $outDir -Force | Out-Null }

$sb.ToString() | Set-Content -Path $OutputFile -Encoding UTF8
Write-Host "==> $OutputFile uretildi: $($files.Count) Component" -ForegroundColor Green
